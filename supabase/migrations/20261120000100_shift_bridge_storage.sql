do $$
begin
    if not exists (select from pg_roles where rolname = 'shift_bridge_web') then
        create role shift_bridge_web nologin nobypassrls;
    end if;
    if not exists (select from pg_roles where rolname = 'shift_bridge_engine') then
        create role shift_bridge_engine nologin nobypassrls;
    end if;
end $$;

create schema shiftbridge_web;
create schema shiftbridge_engine;
revoke all on schema shiftbridge_web, shiftbridge_engine from public;
grant usage on schema shiftbridge_web to shift_bridge_web;
grant usage on schema shiftbridge_engine to shift_bridge_engine;

create table shiftbridge_web.sqlite_import (
    id integer primary key check (id = 1),
    manifest_sha256 text not null,
    verified_at timestamptz not null default now()
);

create table shiftbridge_web.web_users (
    id bigint generated by default as identity primary key,
    username text unique not null,
    password text not null,
    admin integer not null default 0,
    whitelisted integer not null default 0,
    retired integer not null default 0,
    bootstrap_password text,
    personal_workspace integer not null default 0
);
create table shiftbridge_web.web_sessions (
    token text primary key, user_id bigint not null references shiftbridge_web.web_users(id), expires bigint not null
);
create table shiftbridge_web.web_preferences (
    user_id bigint primary key references shiftbridge_web.web_users(id),
    default_location text not null default '', place_type text not null default ''
);
create table shiftbridge_web.web_events (
    id bigint generated by default as identity primary key,
    username text not null, category text not null, feature text not null, result text not null, day text not null,
    created_at text not null default to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
create index web_events_category on shiftbridge_web.web_events(category, id);
create index web_events_quota on shiftbridge_web.web_events(username, category, day, result);

create table shiftbridge_web.work_logs (
    workspace_id bigint not null default nullif(current_setting('shift_bridge.workspace_id', true), '')::bigint,
    id bigint generated by default as identity,
    raw_text text not null, execution_time text, operator text, device_id text, ticket_no text, incident_type text,
    cause text, action_taken text, result text, status text default '미완료', follow_up text, remarks text,
    audio_source text, missing_alerts text, priority_score integer default 50, priority_tier text default 'P3',
    created_at text default to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    search_vector tsvector generated always as (to_tsvector('simple'::regconfig,
        coalesce(raw_text, '') || ' ' || coalesce(device_id, '') || ' ' || coalesce(ticket_no, '') || ' ' ||
        coalesce(incident_type, '') || ' ' || coalesce(action_taken, '') || ' ' || coalesce(follow_up, ''))) stored,
    primary key (workspace_id, id)
);
create index work_logs_search on shiftbridge_web.work_logs using gin (search_vector);
create table shiftbridge_web.handover_reports (
    workspace_id bigint not null default nullif(current_setting('shift_bridge.workspace_id', true), '')::bigint,
    id bigint generated by default as identity,
    shift_title text not null, outgoing_shift text, incoming_shift text, author text, status text default '검토대기',
    summary text, completed_tasks text, pending_tasks text, critical_alerts text, parts_awaiting text,
    follow_up_tasks text, carried_over_tasks text, next_shift_actions text, raw_markdown text,
    approved_by text, approved_at text,
    created_at text default to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    primary key (workspace_id, id)
);
create table shiftbridge_web.technical_documents (
    workspace_id bigint not null default nullif(current_setting('shift_bridge.workspace_id', true), '')::bigint,
    id bigint generated by default as identity,
    filename text not null, category text, summary text, key_points text, full_content text,
    created_at text default to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    primary key (workspace_id, id)
);
create table shiftbridge_web.missing_queries (
    workspace_id bigint not null default nullif(current_setting('shift_bridge.workspace_id', true), '')::bigint,
    id bigint generated by default as identity,
    work_log_id bigint, question text not null, missing_field text, operator_reply text, status text default '답변대기',
    created_at text default to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    primary key (workspace_id, id)
);
create table shiftbridge_web.audit_trails (
    workspace_id bigint not null default nullif(current_setting('shift_bridge.workspace_id', true), '')::bigint,
    id bigint generated by default as identity,
    operator text, action text not null, target text, detail text,
    created_at text default to_char(now() at time zone 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    primary key (workspace_id, id)
);

alter table shiftbridge_web.web_preferences enable row level security;
alter table shiftbridge_web.web_preferences force row level security;
create policy own_preferences on shiftbridge_web.web_preferences to shift_bridge_web
    using (user_id = nullif(current_setting('shift_bridge.account_id', true), '')::bigint)
    with check (user_id = nullif(current_setting('shift_bridge.account_id', true), '')::bigint);

do $$
declare name text;
begin
    foreach name in array array['work_logs', 'handover_reports', 'technical_documents', 'missing_queries', 'audit_trails'] loop
        execute format('alter table shiftbridge_web.%I enable row level security', name);
        execute format('alter table shiftbridge_web.%I force row level security', name);
        execute format('create policy own_workspace on shiftbridge_web.%I to shift_bridge_web
            using (workspace_id = nullif(current_setting(''shift_bridge.workspace_id'', true), '''')::bigint)
            with check (workspace_id = nullif(current_setting(''shift_bridge.workspace_id'', true), '''')::bigint)', name);
    end loop;
end $$;

grant select on shiftbridge_web.sqlite_import to shift_bridge_web, shift_bridge_engine;
grant usage on schema shiftbridge_web to shift_bridge_engine;
grant select, insert, update on shiftbridge_web.web_users, shiftbridge_web.web_events to shift_bridge_web;
grant select, insert, delete on shiftbridge_web.web_sessions to shift_bridge_web;
grant select, insert, delete on shiftbridge_web.web_preferences to shift_bridge_web;
grant update (default_location, place_type) on shiftbridge_web.web_preferences to shift_bridge_web;
grant select, insert, update, delete on shiftbridge_web.work_logs, shiftbridge_web.handover_reports,
    shiftbridge_web.technical_documents, shiftbridge_web.missing_queries, shiftbridge_web.audit_trails to shift_bridge_web;
grant usage on all sequences in schema shiftbridge_web to shift_bridge_web;

create table shiftbridge_engine.records (
    id bigint generated by default as identity primary key,
    created text not null, body text not null, approved integer not null default 0, embedding text, embed_model text
);
create table shiftbridge_engine.reports (
    id bigint generated by default as identity primary key, created text not null, body text not null,
    approved integer not null default 0
);
create table shiftbridge_engine.documents (
    id bigint generated by default as identity primary key,
    created text not null, name text not null, page integer, text text not null
);
create table shiftbridge_engine.usage (
    id bigint generated by default as identity primary key,
    created text not null, task text, model text, input_tokens bigint, output_tokens bigint,
    thinking_tokens bigint, total_tokens bigint
);
grant select, insert, update on shiftbridge_engine.records, shiftbridge_engine.reports to shift_bridge_engine;
grant select, insert on shiftbridge_engine.documents, shiftbridge_engine.usage to shift_bridge_engine;
grant usage on all sequences in schema shiftbridge_engine to shift_bridge_engine;
